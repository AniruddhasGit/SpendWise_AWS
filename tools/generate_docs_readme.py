TEMPLATE = """\
# docs/ — the SpendWise delivery document set

<!-- GENERATED by tools/generate_docs_readme.py. Counts and the State column are
     computed from the repository tree and the ledger. Do not hand-edit those.
     Regenerate:  py tools/generate_docs_readme.py
     Verify:      py tools/generate_docs_readme.py --check -->

Numbered in **dependency order**. Each folder is derived from the ones above it and **cites them**.
Nothing appears out of thin air: a statement without a source carries an `ASSUMED` flag and can
never become a `MUST`.

```
00 SourceOfTruth ──► 02 BRD ──► 03 PRD ──► 05 Bible ──► 06 DataModel ──► code
       │                                                      ▲
       └──► 01 ADR ────────────────────────────────────────────┘
            every ruling, and proof it landed in each document above
```

| # | Folder | What it is | State |
|---|---|---|---|
{rows}

## The four rules that make this work

**1. Provenance on every line.** Every requirement downstream cites `SRC-001 §n` or an
`APPROVED` ADR. You can trace any sentence back to something the client actually said.

**2. Status law.** `RULED` (decided, cited) · `PROVISIONAL` (written, ruling outstanding) ·
`OPEN` (**escalate, never invent**) · `ASSUMED` (inference, never a constraint). An agent that hits
`OPEN` and fills in something plausible has committed the cardinal sin.

**3. Fail-closed decisions.** Every ADR starts `NOT_DECIDED` + `HOLD_PENDING_DECISION` +
`NOT_RELEASED`. **Silence never means approval.** Accepted decisions are immutable — a reversal is a
new superseding record, never an edit. `SW-ADR-004` is the worked example: superseded one hour
later, retained unedited and marked.

A supersession is itself a claim, and it gets checked: `SW-ADR-132` records three links that
resolved but were not true, one of which had silently withdrawn a live decision.

**4. Incorporation is tracked, not assumed.** The ledger's `included_in_brd` / `_prd` / `_bible` /
`_datamodel` columns prove a decision actually *landed* in each document rather than being decided
and forgotten. They are **derived from the citations present in each target**, never asserted:
{inc_brd} records land in the BRD, {inc_prd} in the PRD, {inc_bible} in the Bible, {inc_dm} in the
data model.

## Fingerprints

`00 SourceOfTruth/fingerprints.json` holds a SHA-256 per frozen source.
**If a hash changes, every artifact derived from it is invalid and must be re-derived** — never
silently reused.

A hash comparison is the *weaker* guarantee: it cannot see content a spec never contained, which is
how the isolation hole `SW-ADR-129` closes survived inside a file whose banner said GENERATED. The
stronger check regenerates and compares content.

## Where the open questions live

`CONSTITUTION.md` **Article X**, which carries {openx} rows. All were adjudicated on 2026-08-05
(`SW-ADR-091`…`128`), so no behaviour is unruled. `OPEN-NAME-01` is the one that matters formally:
until a named human signs the ratification block, the Constitution is **UNADOPTED** and all
{adr_total} ADRs carry a "recorded while ungoverned" caveat.

## Reading rules

- For **decision status**, trust the ledger. For **document versions**, trust the files on disk.
  For **paths**, trust the repo tree — never a path quoted in prose.
- Authority on conflict: raw `SRC-001` → a client ruling → an `APPROVED` ADR → PRD → BRD → Bible →
  everything else. **Stricter always wins.**
- **This index included.** It was hand-maintained until 2026-08-05 and drifted in eight places
  while being the first thing a session reads. It is now computed.
"""


def facts():
    def rd(*p):
        try:
            with open(os.path.join(ROOT, *p), encoding="utf-8") as f:
                return f.read()
        except OSError:
            return ""

    led = list(csv.DictReader(io.StringIO(rd("docs", "01 ADR", "ADR_DECISION_RELEASE_LEDGER.tsv")),
                              delimiter="\t"))
    live = sum(1 for r in led if r["decision_status"] == "APPROVED")
    bible = list(csv.DictReader(io.StringIO(rd("docs", "05 Bible", "SpendWise_Bible.csv"))))
    neg = list(csv.DictReader(io.StringIO(rd("docs", "09 NegativeTesting", "SIT_NegativeCases.tsv")),
                              delimiter="\t"))
    sit = list(csv.DictReader(io.StringIO(rd("docs", "08 SIT", "SIT_TestCases.tsv")), delimiter="\t"))
    src = rd("docs", "00 SourceOfTruth", "SRC-001_requirements_2026-08-05.md")
    brd = rd("docs", "02 BRD", "SpendWise_BRD.md")
    prd = rd("docs", "03 PRD", "SpendWise_PRD.md")

    def inc(col):
        return sum(1 for r in led if r.get(col) == "INCLUDED")

    return dict(
        adr_total=len(led), adr_live=live, adr_dead=len(led) - live,
        errata=len(set(re.findall(r"^\*\*(E-\d+) ·", src, re.M))),
        brd=len(set(re.findall(r"^\|\s*`([RN]-[A-Z]+-\d+)`", brd, re.M))),
        prd=len(set(re.findall(r"\*\*`(P-[A-Z]+-\d+)`", prd))),
        stories=sum(1 for b in bible if b.get("Type") == "Story"),
        epics=sum(1 for b in bible if b.get("Type") == "Epic"),
        ac=sum(len([x for x in (b.get("AcceptanceCriteria") or "").split("|") if x.strip()])
               for b in bible),
        sit=len(sit), neg=len(neg),
        xp=sum(1 for r in neg if r.get("attack_class") == "cross-person"),
        sev1=sum(1 for r in neg if r.get("severity") == "SEV-1"),
        openx=len(set(re.findall(r"^\|\s*`(OPEN-[A-Z0-9-]+)`", rd("CONSTITUTION.md"), re.M))),
        inc_brd=inc("included_in_brd"), inc_prd=inc("included_in_prd"),
        inc_bible=inc("included_in_bible"), inc_dm=inc("included_in_datamodel"),
    )


def state_of(folder):
    """A folder's state is what is in it, not what someone typed."""
    d = os.path.join(ROOT, "docs", folder)
    if not os.path.isdir(d):
        return "missing"
    real = [f for r, _, fs in os.walk(d) for f in fs if f != ".gitkeep"]
    if not real:
        return "placeholder"
    return "**written**"


def render():
    f = facts()
    rows = []
    for folder, num, name, blurb in BLURB:
        rows.append("| %s | **%s** | %s | %s |" % (num, name, blurb.format(**f), state_of(folder)))
    rows.append("| 15 | **ChangeRequest** · 20 **UAT** · 35 **Hypercare** · 40 **AMS** | "
                "Lifecycle. | placeholders |")
    return TEMPLATE.format(rows="\n".join(rows), **f)


def main():
    generated = render()
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                committed = f.read()
        except FileNotFoundError:
            print("FAIL  docs/README.md does not exist")
            return 1
        if committed != generated:
            print("FAIL  docs/README.md has drifted from the repository tree.")
            import difflib
            for line in list(difflib.unified_diff(
                    committed.splitlines(), generated.splitlines(),
                    "committed", "computed", lineterm="", n=0))[:24]:
                print("      " + line)
            return 1
        print("PASS  docs/README.md matches the tree and the ledger.")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(generated)
    print("wrote docs/README.md (%d bytes)" % len(generated))
    return 0


if __name__ == "__main__":
    sys.exit(main())
