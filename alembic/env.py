"""Alembic environment. Runs as the OWNER role, never the runtime role.

Three things here are load-bearing and each fails silently if omitted:

1. **`MIGRATION_DATABASE_URL`, not `DATABASE_URL`.** Migrations run as
   `spendwise_owner`; traffic runs as `spendwise_app`. Running migrations as the
   runtime role would mean the runtime role owns the tables — and an owner can
   `ALTER TABLE ... NO FORCE ROW LEVEL SECURITY`, which is the isolation
   guarantee removing itself (`SW-ADR-081`).

2. **`SET LOCAL row_security = off`.** `FORCE ROW LEVEL SECURITY` subjects the
   table owner to the policies too — that is the whole point of `FORCE`. So a
   *data* migration run by the owner would match **zero rows** and report
   success. The runtime role cannot do this: it lacks `BYPASSRLS`, so the
   guarantee is unaffected.

3. **`pg_advisory_xact_lock`.** Two containers starting at once both run
   `alembic upgrade head`. Without the lock they race, and the loser fails on a
   duplicate object at a point that leaves the schema half-applied (`P-OPS-02`).
"""
from __future__ import annotations

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool, text
from sqlalchemy.ext.asyncio import async_engine_from_config

from app.core.settings import get_settings

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# Autogenerate is deliberately NOT wired to a MetaData object. `datamodel.json`
# is the spec of record and `schema.sql` is generated from it (`SW-ADR-066`);
# a migration autogenerated from ORM models would make the models the source of
# truth and let the two drift silently. Migrations here are written against the
# generated DDL, and `generate.py --check` is what proves they agree.
target_metadata = None

# One arbitrary but STABLE key. Derived from a literal rather than a hash of
# anything, so it cannot change between releases and let two versions of the app
# hold different locks while thinking they hold the same one.
MIGRATION_LOCK_KEY = 0x5350_454E_4457_5345 & 0x7FFF_FFFF_FFFF_FFFF   # "SPENDWSE"


def _url() -> str:
    """The OWNER's URL. Asserted, not assumed — pointing this at the runtime
    role is the mistake that produces a schema owned by the wrong role, and it
    is silent until the day-one gate fails for a reason nobody can see."""
    s = get_settings()
    url = s.MIGRATION_DATABASE_URL.get_secret_value()
    if url == s.DATABASE_URL.get_secret_value():
        raise RuntimeError(
            "MIGRATION_DATABASE_URL and DATABASE_URL are the same connection. "
            "They must be two different roles (SW-ADR-081): the owner migrates, "
            "the runtime role serves. One role for both means the runtime "
            "connection owns the tables, and an owner can disable FORCE ROW "
            "LEVEL SECURITY on itself."
        )
    return url


def run_migrations_offline() -> None:
    """`--sql` mode: emit the DDL without connecting.

    Useful for review and for handing SQL to someone who runs it by hand — but
    the advisory lock and `row_security = off` cannot be expressed here, so
    offline output is for READING, not for applying to a live database.
    """
    context.configure(
        url=_url(), target_metadata=target_metadata, literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def _do_run(connection) -> None:
    # `SET LOCAL row_security = off` is DELIBERATELY ABSENT, and its absence is
    # the correction.
    #
    # `SW-ADR-081` says to set it so a data migration run by the owner is not
    # silently filtered by FORCE ROW LEVEL SECURITY. **That is not what the
    # setting does.** PostgreSQL: "When set to off, queries fail which would
    # otherwise apply at least one policy." It does not bypass RLS — only
    # BYPASSRLS does, and the owner deliberately does not hold it.
    #
    # So it turns a silently-filtered query into a hard error, which is better,
    # but it also broke the baseline migration outright: planning the
    # `admin_expense_stats` function body touches `expenses`, and with
    # row_security=off that CREATE FUNCTION failed with
    # "query would be affected by row-level security policy for table expenses".
    #
    # DDL does not read rows, so this migration needs nothing. A future DATA
    # migration that must touch protected tables has to say so explicitly —
    # `ALTER TABLE … NO FORCE ROW LEVEL SECURITY` around the change, or setting
    # `app.user_id` per row. Neither is silent, which is the point.
    connection.execute(text("SELECT pg_advisory_xact_lock(:k)"),
                       {"k": MIGRATION_LOCK_KEY})
    context.configure(connection=connection, target_metadata=target_metadata)
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    section = config.get_section(config.config_ini_section, {})
    section["sqlalchemy.url"] = _url()
    engine = async_engine_from_config(section, prefix="sqlalchemy.", poolclass=pool.NullPool)
    async with engine.connect() as conn:
        await conn.run_sync(_do_run)
        await conn.commit()
    await engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
