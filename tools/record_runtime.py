#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Emit `docs/30 Deployment/RUNTIME_VERSIONS.md` from the actual environment.

The client builds the container by hand (`SW-ADR-005`), so this session never
writes a Dockerfile. What it owes instead is **the exact facts that Dockerfile
must pin** — and a hand-typed version table is the same drifting artifact this
project has now filed six ADRs about. So it is generated from the interpreter
and the lockfile that are actually installed.

    py tools/record_runtime.py            write the record
    py tools/record_runtime.py --check    verify it matches this environment

Run it with the PROJECT VENV's interpreter, not the system one — the whole
point is to record what the venv resolved to.
"""
from __future__ import annotations

import os
import platform
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "30 Deployment" / "RUNTIME_VERSIONS.md"
LOCK = ROOT / "requirements.lock"

# The stack SW-ADR-016 locks by name. Everything else in the lockfile is a
# transitive dependency — pinned, but not a decision anyone made.
RULED = ["fastapi", "uvicorn", "sqlalchemy", "asyncpg", "alembic", "pydantic",
         "pydantic-settings", "pyjwt", "bcrypt", "boto3", "python-dateutil"]
TEST_STACK = ["pytest", "pytest-asyncio", "httpx", "playwright"]


def pinned() -> dict[str, str]:
    """Parse `requirements.lock`.

    Read as `utf-8-sig`, not `utf-8`. PowerShell's `Out-File -Encoding utf8`
    writes a BOM, so the first line arrives as `\\ufeffalembic==1.19.0`, the
    regex misses it, and this record reported a pinned, installed package as
    **NOT INSTALLED** — on the line that would have gone into a Dockerfile.
    `write_lock()` now writes the file itself, without a BOM; this stays
    tolerant so a hand-regenerated lockfile cannot reintroduce the bug.
    """
    out: dict[str, str] = {}
    if LOCK.is_file():
        for line in LOCK.read_text(encoding="utf-8-sig").splitlines():
            m = re.match(r"^([A-Za-z0-9._-]+)==(.+)$", line.strip())
            if m:
                out[m.group(1).lower().replace("_", "-")] = m.group(2)
    return out


def write_lock() -> int:
    """Regenerate `requirements.lock` from THIS interpreter, BOM-free."""
    r = subprocess.run([sys.executable, "-m", "pip", "freeze", "--exclude-editable"],
                       capture_output=True, text=True, timeout=180)
    lines = sorted(l.strip() for l in r.stdout.splitlines() if "==" in l)
    LOCK.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return len(lines)


def postgres_version() -> str:
    for base in sorted(Path("C:/Program Files/PostgreSQL").glob("*"), reverse=True) \
            if Path("C:/Program Files/PostgreSQL").is_dir() else []:
        psql = base / "bin" / "psql.exe"
        if psql.is_file():
            try:
                r = subprocess.run([str(psql), "--version"], capture_output=True,
                                   text=True, timeout=20)
                return r.stdout.strip() or "unknown"
            except Exception:
                pass
    return "not detected on this machine"


def render() -> str:
    p = pinned()
    py_v = platform.python_version()
    major_minor = ".".join(py_v.split(".")[:2])

    def rows(names: list[str]) -> str:
        return "\n".join(
            "| `%s` | `%s` |" % (n, p.get(n, "**NOT INSTALLED**")) for n in names)

    return f"""# Runtime versions — what the container must pin

<!-- GENERATED by tools/record_runtime.py from the project venv and
     requirements.lock. Do not hand-edit — regenerate.
     Verify:  py tools/record_runtime.py --check                              -->

**The build session does not write the Dockerfile** (`SW-ADR-005`). This is what it
owes instead: the exact facts that Dockerfile has to reproduce, taken from the
interpreter and lockfile actually installed rather than typed from memory.

## The interpreter

| | |
|---|---|
| **Python** | **{py_v}** |
| Implementation | {platform.python_implementation()} (`{sys.implementation.cache_tag}`) |
| Ruled by | `SW-ADR-016` — *"do not substitute, even for something better"* |
| `pyproject.toml` | `requires-python = ">=3.12,<3.13"` |

**Base image: `python:{py_v}-slim`.** Pin the patch, not just `3.12` — a floating
minor tag is a build that changes underneath you between two deploys of the same
commit, which is the class of problem this whole document set exists to prevent.

> Recorded honestly: this machine also carries Python {'3.14' if major_minor != '3.14' else '3.12'},
> which is **not** the ruled version. The venv at `.venv/` is 3.12 and every test
> result in this repository was produced by it. If a future session reports a
> green suite from a different interpreter, that result does not count.

## The stack `SW-ADR-016` locks by name

| Package | Version |
|---|---|
{rows(RULED)}

## The test stack (`SW-ADR-139` / `CV-16`)

Not in the runtime image — these belong to CI and the developer machine only.

| Package | Version |
|---|---|
{rows(TEST_STACK)}

## Everything else

`requirements.lock` pins **{len(p)} packages** including every transitive
dependency. The image installs from that file, never from `pyproject.toml`
ranges — ranges resolve differently on different days.

```dockerfile
COPY requirements.lock .
RUN pip install --no-cache-dir -r requirements.lock
```

## Database

| | |
|---|---|
| Local development | {postgres_version()} |
| Minimum required | PostgreSQL **14** (`datamodel.json`) |
| Production | AWS RDS — **the client's choice, and it should match the local major** |

The features this schema depends on are old and safe — `GENERATED ALWAYS AS
IDENTITY`, `FORCE ROW LEVEL SECURITY`, `generate_series`, partial indexes. The
version that matters is **whether local and RDS agree**, not how new either is.
A local 18 against an RDS 14 is a difference that shows up once, in production,
in something nobody tested.

## What this does not cover

The Node/Vite toolchain for `client/` is not pinned here — no frontend exists
yet. It joins this record when it does.
"""


def main() -> int:
    if "--check" not in sys.argv:
        print("wrote requirements.lock (%d packages, no BOM)" % write_lock())
    text = render()
    if "--check" in sys.argv:
        if not OUT.is_file():
            print("FAIL  %s does not exist" % OUT.name)
            return 1
        if OUT.read_text(encoding="utf-8") != text:
            print("FAIL  RUNTIME_VERSIONS.md does not match this environment.")
            print("      Either the venv changed and the record is stale, or you are")
            print("      running this with the wrong interpreter. Regenerate with the")
            print("      project venv:  .venv/Scripts/python tools/record_runtime.py")
            return 1
        print("PASS  RUNTIME_VERSIONS.md matches the installed environment.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s" % OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main())
